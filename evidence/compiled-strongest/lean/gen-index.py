#!/usr/bin/env python3
"""Regenerate SummitsAudit.lean and the §23 theorem index from the sources.

Every non-private `theorem` or `lemma` in every module listed in build-and-audit.sh gets a
`#print axioms` line, so the audit covers everything compiled, not a chosen
subset. The index (module -> theorems) is written into
inserts/23-machine-checked-canon.md between the BEGIN/END THEOREM INDEX markers.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SNUFFY = os.path.join(HERE, "Snuffy")
INSERT = os.path.join(HERE, "..", "inserts", "23-machine-checked-canon.md")
BEGIN, END = "<!-- BEGIN THEOREM INDEX -->", "<!-- END THEOREM INDEX -->"


def modules():
    src = open(os.path.join(HERE, "build-and-audit.sh")).read()
    return re.search(r"^MODULES=\((.*)\)$", src, re.M).group(1).split()


def theorems(path):
    """Full names of the non-private theorems and lemmas declared in a module."""
    stack, out = [], []
    for line in open(path):
        if m := re.match(r"\s*namespace\s+(\S+)", line):
            stack.append(("ns", m.group(1)))
        elif m := re.match(r"\s*(?:noncomputable\s+)?section(?:\s+(\S+))?\s*$", line):
            stack.append(("sec", m.group(1) or ""))
        elif m := re.match(r"\s*end(?:\s+(\S+))?\s*$", line):
            if stack:
                stack.pop()
        elif m := re.match(r"(?:@\[[^\]]*\]\s*)?(?:protected\s+)?(?:theorem|lemma)\s+(\S+)", line):
            ns = ".".join(n for k, n in stack if k == "ns")
            out.append(f"{ns}.{m.group(1)}" if ns else m.group(1))
    return out


def main():
    mods = modules()
    index = {m: theorems(os.path.join(SNUFFY, f"{m}.lean")) for m in mods}
    audit = ["-- Generated by gen-index.py: every theorem of every audited module.", ""]
    audit += [f"import Snuffy.{m}" for m in mods] + [""]
    for m in mods:
        audit.append(f"-- {m}")
        audit += [f"#print axioms {t}" for t in index[m]]
    open(os.path.join(HERE, "SummitsAudit.lean"), "w").write("\n".join(audit) + "\n")

    rows = ["## 23.A Complete theorem index", "",
            "Generated from the sources by `lean/gen-index.py`; every theorem listed here is "
            "kernel-checked and axiom-audited by `lean/build-and-audit.sh`.", "",
            "| Module | Theorems |", "| --- | --- |"]
    for m in mods:
        names = ", ".join(f"`{t.split('.')[-1]}`" for t in index[m]) or "(definitions only)"
        rows.append(f"| `{m}` | {names} |")
    block = BEGIN + "\n" + "\n".join(rows) + "\n" + END
    text = open(INSERT).read()
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    open(INSERT, "w").write(text)
    print(f"modules {len(mods)}, theorems {sum(len(v) for v in index.values())}")


if __name__ == "__main__":
    main()
