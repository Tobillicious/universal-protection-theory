"""Replay this book proof segment with the pinned Lean compiler."""
from pathlib import Path
import hashlib
import json
import os
import shutil
import subprocess
from proof_audit import verify_axiom_reports

root = Path(__file__).resolve().parent
proofs = root / "proofs"
source_lock = json.loads((root / "source-lock.json").read_text())
registry = json.loads((root / "proof-registry.json").read_text())
for relative, expected in source_lock["upstream_copied_blobs"].items():
    data = (root / relative).read_bytes()
    actual = hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
    if actual != expected:
        raise SystemExit("Source identity mismatch: " + relative)
pin = "leanprover/lean4:v4.35.0"
elan = shutil.which("elan")
if not elan:
    raise SystemExit("Install elan and the pinned " + pin + " toolchain.")
lean = [elan, "run", pin, "lean"]
env = os.environ.copy()
env["LEAN_PATH"] = str(proofs)
commands = [
    ["--version"],
    ["-o", "Snuffy/UPTLawLife.olean", "Snuffy/UPTLawLife.lean"],
    ["-o", "Snuffy/BookCanonicalDominance.olean", "Snuffy/BookCanonicalDominance.lean"],
] + [["-o", module.replace(".", "/") + ".olean",
       module.replace(".", "/") + ".lean"] for module in registry]
lines = ["upstream_main=" + source_lock["reviewed_main_sha"],
    "upstream copied source blobs verified"]
for args in commands:
    result = subprocess.run(lean + args, cwd=proofs, env=env,
        text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    lines.extend(["$ lean " + " ".join(args), result.stdout.rstrip(),
        "exit_code=" + str(result.returncode)])
    if result.returncode:
        text = "\n".join(lines) + "\n"
        (root / "lean-receipt.txt").write_text(text)
        print(text)
        raise SystemExit(result.returncode)
expected = [name for names in registry.values() for name in names]
auditor = proofs / "ProofAudit.lean"
auditor.write_text("\n".join(
    ["-- Generated by replay.py; audit actual compiled declarations."] +
    ["import " + module for module in registry] +
    ["#print axioms " + name for name in expected]
) + "\n")
result = subprocess.run(lean + [str(auditor)], cwd=proofs, env=env,
    text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
lines.extend(["$ lean ProofAudit.lean", result.stdout.rstrip(),
    "exit_code=" + str(result.returncode)])
if result.returncode:
    (root / "lean-receipt.txt").write_text("\n".join(lines) + "\n")
    raise SystemExit(result.returncode)
try:
    reports = verify_axiom_reports(result.stdout, expected)
except ValueError as error:
    lines.append("REJECTED: " + str(error))
    (root / "lean-receipt.txt").write_text("\n".join(lines) + "\n")
    raise SystemExit(str(error))
summary = {
    "local_Lean_version": "4.35.0",
    "declarations": len(reports),
    "axiom_free": sum(not dependencies for dependencies in reports.values()),
    "standard_classical_foundations": sum(bool(dependencies) for dependencies in reports.values()),
    "admitted_or_custom_axioms": False,
    "theorem_parameters_remain_explicit": True,
    "unconditional_actual_world_proof_complete": False,
    "declaration_axioms": reports,
}
(root / "verification-summary.json").write_text(json.dumps(summary, indent=2) + "\n")
lines.append("STRICT AXIOM ALLOWLIST AND EXACT DECLARATION REGISTRY: PASS")
for relative in ["proofs/Snuffy/UPTLawLife.lean",
        "proofs/Snuffy/BookCanonicalDominance.lean",
        "proofs/HumanAICoexistence.lean",
        "proofs/CapstoneCompatibility.lean",
        "proofs/UniversalGuardianFixedPoint.lean",
        "proofs/KoruBoundaryWitness.lean",
        "proofs/GuardianRobustness.lean",
        "proofs/HostileCountermodels.lean",
        "proofs/ProofAudit.lean", "proof-registry.json", "proof_audit.py"]:
    data = (root / relative).read_bytes()
    blob = hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
    lines.append("git_blob " + blob + " " + relative)
    lines.append("sha256 " + hashlib.sha256(data).hexdigest() + " " + relative)
text = "\n".join(lines) + "\n"
(root / "lean-receipt.txt").write_text(text)
print(text)

